export type StringKey = keyof typeof strings;

export function translate(lang: Language, key: StringKey, vars?: Record<string, string | number>): string {
  const entry = strings[key] as { en: string; he: string } | undefined;
  let s = entry ? entry[lang] ?? entry.en : key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

export const LangContext = createContext<Language>("en");

export function useLang(): Language {
  return useContext(LangContext);
}

/** t("key", { n: 3 }) — bound to the room language from context. */
export function useT() {
  const lang = useLang();
  return (key: StringKey, vars?: Record<string, string | number>) => translate(lang, key, vars);
}

export function dirFor(lang: Language): "rtl" | "ltr" {
  return lang === "he" ? "rtl" : "ltr";
}

/** Apply lang/dir on <html> so CSS logical properties and fonts follow. */
export function applyDocumentLanguage(lang: Language) {
  const el = document.documentElement;
  el.setAttribute("lang", lang);
  el.setAttribute("dir", dirFor(lang));
}
